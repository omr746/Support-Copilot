"""Request and response schemas for Support Copilot API endpoints."""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class AskRequest(BaseModel):
    """Payload for customer support query to /ask."""

    model_config = ConfigDict(extra="forbid")

    question: str = Field(
        ...,
        min_length=1,
        description="The customer's support question or message.",
    )
    session_id: str | None = Field(
        default=None,
        description="Optional conversation session ID for tracking turns.",
    )


class AskResponse(BaseModel):
    """Response returned by the /ask endpoint."""

    model_config = ConfigDict(extra="ignore")

    answer: str = Field(description="Answer text generated by the answering model.")
    model: str = Field(description="Specific model identifier that generated the answer.")
    provider: str = Field(description="Provider name that answered the request.")
    session_id: str | None = Field(
        default=None,
        description="Echoed session ID if provided in the request.",
    )


class HealthResponse(BaseModel):
    """Liveness probe response for /healthz."""

    model_config = ConfigDict(extra="ignore")

    status: str = Field(default="ok", description="Liveness state.")


class ReadyResponse(BaseModel):
    """Readiness probe response for /readyz."""

    model_config = ConfigDict(extra="ignore")

    status: str = Field(description="Readiness state ('ready' or 'unavailable').")
    checks: dict[str, Any] = Field(
        default_factory=dict,
        description="Health status of individual system dependencies.",
    )
